// Builds supabase/seed.sql from the starter card list.
// Run: npx tsx scripts/make-seed.ts
import { writeFileSync } from "node:fs";
import { STARTER_CARDS } from "../src/lib/starter-cards";
import { COMMUNITY_TOTAL, makeSpots, weaknessesOf } from "../src/lib/game";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (xs: (string | number)[]) =>
  `'{${xs.map((x) => (typeof x === "number" ? x : `"${x}"`)).join(",")}}'`;

const rows = STARTER_CARDS.map((c) => {
  const total = c.total ?? COMMUNITY_TOTAL;
  const spots = makeSpots(`cosme-starter-${c.number}-${c.name}`, total);
  const weak = c.weaknesses ?? weaknessesOf(c.type);
  return `(${c.number}, ${q(c.name)}, ${q(c.type)}, ${q(c.move)}, ${q(c.description)}, ${q(c.art ?? null)}, ${total}, ${arr(spots)}, ${arr(weak)}, ${q(c.rarity ?? "common")}, 'starter')`;
});

const sql = `-- 36 COSME starter cards. Generated by scripts/make-seed.ts, safe to run again.
insert into public.cards (number, name, type, move, description, art_url, total, spots, weaknesses, rarity, status) values
${rows.join(",\n")}
on conflict (number) do update set
  name = excluded.name, type = excluded.type, move = excluded.move, description = excluded.description,
  art_url = excluded.art_url, total = excluded.total, spots = excluded.spots,
  weaknesses = excluded.weaknesses, rarity = excluded.rarity, status = excluded.status;
`;

writeFileSync("supabase/seed.sql", sql);
console.log(`Wrote ${rows.length} cards to supabase/seed.sql`);
